import { readFileSync, writeFileSync } from 'node:fs';
import ts from 'typescript';
const moduleSource = readFileSync('src/lib/redirects/inventory.ts', 'utf8').replace(
  /^export\s+/gm,
  '',
);
const compiled = ts.transpileModule(moduleSource, {
  compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext },
}).outputText;
const { parseStaticRedirects, parseClientRedirects } = new Function(
  compiled + '\nreturn {parseStaticRedirects,parseClientRedirects};',
)();
const rows = [
  ...parseStaticRedirects(readFileSync('public/_redirects', 'utf8')),
  ...parseClientRedirects(readFileSync('src/routes.tsx', 'utf8')),
];
const output =
  '// Generated by scripts/sync-redirect-inventory-manifest.mjs --write.\n// Source definitions only; client patterns do not represent resolved visitor targets.\nexport const deployedRedirectManifest = ' +
  JSON.stringify(rows, null, 2) +
  ' as const;\n';
const path = 'supabase/functions/_shared/redirect-inventory-manifest.ts';
if (process.argv.includes('--write')) writeFileSync(path, output);
else if (readFileSync(path, 'utf8') !== output)
  throw new Error(
    'Redirect inventory manifest differs from current source. Run node scripts/sync-redirect-inventory-manifest.mjs --write and commit the generated file.',
  );
console.log(
  'Redirect manifest: ' +
    rows.length +
    ' actual static/client rule definitions match the shared parsers.',
);
